#!/usr/bin/env python3
"""Generate data/reference/rating_schedule.json from a saved eCFR snapshot of 38 CFR Part 4.

Everything comes from the regulation's own text; nothing is typed by hand:

* which codes are current: a code is current only if its section's schedule rates it
  (a table row, or the 38 CFR 4.130 list). Appendix B, the index, still lists some codes
  the schedule dropped (e.g. 6067-6079 since the 2008 eye revision); those are SUPERSEDED
  with a note saying so. Codes Appendix B marks "[Removed]" are SUPERSEDED with the
  removal date from Appendix A;
* names, body systems and subsections: Appendix B (Numerical Index of Disabilities);
* each code's own rating rows: the rows under that code in its section's table;
* shared formulas (mental disorders, spine, heart, skin, eye, seizures, the genitourinary
  dysfunctions, ...): every rated block that is not under a code, titled by the row,
  caption or section heading above it;
* which codes a formula rates, only where the regulation says so in words:
  - the formula's title or scope line lists the codes ("For DCs 7806, 7809, 7813-7816 ..."),
  - a note says "diagnostic codes 9201 to 9440 will be evaluated using the ... Formula ...",
  - the code's own text says "Evaluate under / Rate under / Rate as / use the ...",
  - the heart table's caption: "Unless otherwise directed, use this general rating formula",
  - 38 CFR 4.130 lists the codes immediately before the formula that rates them.

Where a table has two rating columns (38 CFR 4.69: dominant/major and non-dominant/minor),
percent is the major side and percent_minor the minor side. A row without a rating that
sits deeper than the rating above it is part of that criterion; one that introduces the
next ratings is carried as their context; notes and cross-references ("Rate as ...") are
kept verbatim in the code's notes. Values under a column that is not a rating (diplopia's
"equivalent visual acuity") stay text. Rows are SOURCE_CHECKED: generated from the primary
source and pinned by tests; VERIFIED needs a named human reviewer.

  python3 scripts/build_rating_schedule.py           # regenerate the JSON
  python3 scripts/build_rating_schedule.py --check   # fail if the JSON is not what the snapshot gives
"""
