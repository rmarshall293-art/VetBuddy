#!/usr/bin/env python3
"""Validate data/reference/*.json and generate database/seeds/0011_reference.sql.

  python3 scripts/build_reference.py            # validate + write the seed
  python3 scripts/build_reference.py --check    # fail if the seed is stale (CI)
  DATABASE_ADMIN_URL=... python3 scripts/build_reference.py --load
                                                # apply the seed as schema owner

The seed is a full, idempotent refresh inside one transaction: TRUNCATE every
ref table, then INSERT in dependency order. Re-running it on a loaded
database changes nothing. JSON is the source of truth; the SQL is generated
and committed so reviewers can read exactly what the database will hold.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.domains.reference import corpus  # noqa: E402

SEED = ROOT / "database" / "seeds" / "0011_reference.sql"

ORDER = ("source", "care_type", "conflict", "supersession", "directory_entry", "statistic", "rate", "state_summary",
         "benefit_lead", "duty_authority", "rule_lead", "timeline_window", "education_program", "installation",
         "finding", "governance_rule", "module", "rating_code", "rating_criterion")
JSON_COLS = {"dims", "readings", "counts"}


def lit(col: str, v) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if col in JSON_COLS:
        return "'" + json.dumps(v, sort_keys=True, ensure_ascii=False).replace("'", "''") + "'::jsonb"
    if isinstance(v, list):
        if not v:
            return "'{}'::text[]"
        return "ARRAY[" + ",".join("'" + str(x).replace("'", "''") + "'" for x in v) + "]::text[]"
    return "'" + str(v).replace("'", "''") + "'"


def render(c: corpus.Corpus) -> str:
    out = ["-- GENERATED by scripts/build_reference.py from data/reference/*.json — do not edit.",
           "-- Full idempotent refresh of the V0 reference corpus (migration 0011).",
           "BEGIN;",
           "TRUNCATE " + ", ".join(f"ref.{t}" for t in ORDER) + ", ref.dataset;"]
    for table in ORDER:
        rows = c.tables.get(table, [])
        if not rows:
            continue
        cols = list(rows[0].keys())
        out.append(f"\n-- {table}: {len(rows)} rows")
        for r in rows:
            out.append(f"INSERT INTO ref.{table} ({', '.join(cols)}) VALUES ("
                       + ", ".join(lit(col, r[col]) for col in cols) + ");")
    out.append("\n-- dataset trust cards")
    for d in c.datasets:
        cols = list(d.keys())
        out.append(f"INSERT INTO ref.dataset ({', '.join(cols)}) VALUES (" + ", ".join(lit(k, d[k]) for k in cols) + ");")
    out.append("COMMIT;\n")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    try:
        c = corpus.build()
    except corpus.CorpusError as e:
        print(e, file=sys.stderr)
        return 1
    sql = render(c)
    if "--check" in argv:
        if not SEED.exists() or SEED.read_text() != sql:
            print(f"{SEED.relative_to(ROOT)} is stale: run scripts/build_reference.py", file=sys.stderr)
            return 1
        print("reference seed up to date")
        return 0
    SEED.parent.mkdir(parents=True, exist_ok=True)
    SEED.write_text(sql)
    total = sum(len(v) for v in c.tables.values())
    print(f"wrote {SEED.relative_to(ROOT)}: {total} rows in {len(c.tables)} tables, {len(c.datasets)} datasets")
    if "--load" in argv:
        dsn = os.environ.get("DATABASE_ADMIN_URL")
        if not dsn:
            print("DATABASE_ADMIN_URL is not set", file=sys.stderr)
            return 2
        from app.infra.db import connect
        with connect(dsn) as conn:
            conn.execute_script(sql)
        print("reference corpus loaded")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
