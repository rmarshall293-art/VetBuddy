#!/usr/bin/env python3
"""VA disability compensation rates from saved VA.gov pages.

Reads data/research/federal/va_comp_rates/va_rates_effective_<date>.html (VA.gov's own
"Current veterans disability compensation rates" page and its past-rates page) and

* regenerates va_compensation_2026 in data/reference/compensation.json: every cell of
  VA's table effective 2025-12-01 (veteran alone, with spouse, child, parents, and the
  added amounts), in integer cents;
* checks every cell the 2025 table (va_compensation, effective 2024-12-01) holds against
  VA's table for that period.

  python3 scripts/build_va_rates.py           # rewrite va_compensation_2026
  python3 scripts/build_va_rates.py --check   # fail on any difference (CI)
"""
import argparse, html, json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SNAP = ROOT / "data/research/federal/va_comp_rates"
COMP = ROOT / "data/reference/compensation.json"

# VA row label (start of it) -> our key. Order matters: longer, more specific labels first.
ROWS = [
    ("Veteran alone", "veteran_alone"),
    ("With spouse and 1 parent", "with_spouse_and_1_parent"),
    ("With spouse and 2 parents", "with_spouse_and_2_parents"),
    ("With spouse", "with_spouse"),
    ("With 1 parent", "with_1_parent"),
    ("With 2 parents", "with_2_parents"),
    ("Veteran with", "with_child"),
    ("With 1 child, spouse, and 1 parent", "with_spouse_and_child_and_1_parent"),
    ("With 1 child, spouse and 1 parent", "with_spouse_and_child_and_1_parent"),
    ("With 1 child, spouse, and 2 parents", "with_spouse_and_child_and_2_parents"),
    ("With 1 child, spouse and 2 parents", "with_spouse_and_child_and_2_parents"),
    ("With 1 child and spouse", "with_spouse_and_child"),
    ("With 1 child and 1 parent", "with_child_and_1_parent"),
    ("With 1 child and 2 parents", "with_child_and_2_parents"),
    ("Each additional child under", "each_additional_child_under_18"),
    ("Each additional child over", "each_additional_child_18_23_in_school"),
    ("Spouse rece", "spouse_aid_and_attendance"),      # VA's 2025 page spells it "receving"
]


def _cents(s: str):
    s = s.replace(",", "").replace("$", "").strip()
    return round(float(s) * 100) if re.fullmatch(r"\d+(\.\d{1,2})?", s) else None


def parse(path: Path):
    s = path.read_text(encoding="utf-8")
    eff = re.search(r"[Ee]ffective (December 1, \d{4})", re.sub(r"<[^>]+>", " ", s)).group(1)
    cells = {}
    for body in re.findall(r"<va-table [^>]*>(.*?)</va-table>", s, re.S):
        rows = re.findall(r'<va-table-row slot="([^"]*)">(.*?)</va-table-row>', body, re.S)
        text = lambda r: [html.unescape(re.sub(r"<[^>]+>", "", c)).replace("\xa0", " ").strip()
                          for c in re.findall(r"<span>(.*?)</span>", r, re.S)]
        head = text(next(r for slot, r in rows if slot == "headers"))
        ratings = [int(m.group(1)) if (m := re.search(r"(\d+)%", h)) else None for h in head[1:]]
        for slot, r in rows:
            if slot == "headers":
                continue
            c = text(r)
            if re.fullmatch(r"\d+%", c[0]):                       # the 10%/20% table lists ratings as rows
                cells.setdefault("veteran_alone", {})[c[0][:-1]] = _cents(c[1])
                continue
            key = next((k for p, k in ROWS if c[0].startswith(p)), None)
            if key is None:
                raise SystemExit(f"{path.name}: unknown VA row {c[0]!r}")
            for rt, v in zip(ratings, c[1:]):
                if rt is not None and _cents(v) is not None:
                    cells.setdefault(key, {})[str(rt)] = _cents(v)
    return eff, cells


def build():
    snaps = {p.stem.split("_")[-1]: parse(p) for p in sorted(SNAP.glob("va_rates_effective_*.html"))}
    _, c26 = snaps["2025-12-01"]
    _, c25 = snaps["2024-12-01"]
    alone = {k: c26["veteran_alone"][k] for k in sorted(c26["veteran_alone"], key=int)}
    deps = {k: {r: v[r] for r in sorted(v, key=int)} for k, v in sorted(c26.items()) if k != "veteran_alone"}
    v26 = {
        "rate_set": "va_comp_2026",
        "effective_from": "2025-12-01",
        "status": "SOURCE_CHECKED",
        "sources": ["src.va.comp_rates_2025_12_01"],
        "note": ("Every cell of VA.gov's rate table effective December 1, 2025, generated by scripts/build_va_rates.py "
                 "from the saved page. Dependent amounts start at 30%; 10% and 20% have none. A named reviewer still "
                 "marks the table VERIFIED."),
        "veteran_alone": alone,
        "dependents": deps,
    }
    return v26, c25


def check_2025(comp, c25):
    vc, bad = comp["va_compensation"], []
    table = {"veteran_alone": "veteran_alone", "with_spouse": "with_spouse", "with_spouse_and_one_child": "with_spouse_and_child"}
    for ours, theirs in table.items():
        for r, cents in vc.get(ours, {}).items():
            if r == "0":
                continue
            if c25.get(theirs, {}).get(r) != cents:
                bad.append(f"2025 {ours} {r}%: ours {cents}, VA {c25.get(theirs, {}).get(r)}")
    addon = {"child_under_18_each": "each_additional_child_under_18",
             "child_18_23_in_school_each": "each_additional_child_18_23_in_school",
             "spouse_aid_and_attendance": "spouse_aid_and_attendance"}
    for a in vc["addons"]:
        if c25.get(addon[a["key"]], {}).get(str(a["rating"])) != a["amount_cents"]:
            bad.append(f"2025 {a['key']} {a['rating']}%: ours {a['amount_cents']}, VA {c25.get(addon[a['key']], {}).get(str(a['rating']))}")
    return bad


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    comp = json.loads(COMP.read_text(encoding="utf-8"))
    v26, c25 = build()
    bad = check_2025(comp, c25)
    if a.check:
        if comp["va_compensation_2026"] != v26:
            bad.append("va_compensation_2026 is not what VA's saved table gives")
        if bad:
            sys.exit("\n".join(bad))
        print("VA compensation rates match the saved VA.gov tables")
        return
    if bad:
        sys.exit("\n".join(bad))
    comp["va_compensation_2026"] = v26
    COMP.write_text(json.dumps(comp, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote va_compensation_2026: {sum(len(v) for v in v26['dependents'].values()) + len(v26['veteran_alone'])} cells")


if __name__ == "__main__":
    main()
