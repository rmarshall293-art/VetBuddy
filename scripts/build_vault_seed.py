#!/usr/bin/env python3
"""Generate the 0014 seed from the vault registry, or check it for drift.

    python3 scripts/build_vault_seed.py           # write database/seeds/0014_benefit_vault_seed.sql
    python3 scripts/build_vault_seed.py --check   # exit 1 if the file differs

The seed is idempotent: it upserts every reference row, stamps it with the
registry hash, then prunes rows carrying an older stamp. A VERIFIED mark made
in the database survives a reseed only while the record's content hash is the
one the reviewer saw; otherwise the record falls back to its registry status
(the CHECK constraints refuse anything else). Apply after 0014, in one
transaction, as the migration owner.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTRY_PATH = ROOT / "data" / "reference" / "benefit_vault_registry.json"
SEED_PATH = ROOT / "database" / "seeds" / "0014_benefit_vault_seed.sql"
CHUNK = 200


def lit(value) -> str:
    """A SQL literal for str, int, bool, None and lists of str."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, (list, tuple)):
        return "ARRAY[" + ",".join(lit(v) for v in value) + "]::TEXT[]" if value else "ARRAY[]::TEXT[]"
    text = str(value)
    if "\x00" in text:
        raise ValueError("NUL in seed text")
    return "'" + text.replace("'", "''") + "'"


def upsert(table: str, key: str, columns, rows, update_sql=None) -> list:
    out = []
    for start in range(0, len(rows), CHUNK):
        chunk = rows[start:start + CHUNK]
        values = ",\n  ".join("(" + ", ".join(lit(v) for v in row) + ")" for row in chunk)
        updates = update_sql or ", ".join(f"{c} = EXCLUDED.{c}" for c in columns if c != key)
        out.append(f"INSERT INTO {table} ({', '.join(columns)}) VALUES\n  {values}\n"
                   f"ON CONFLICT ({key}) DO UPDATE SET {updates};")
    return out


def render(registry: dict) -> str:
    sha = registry["integrity"]["sha256"]
    parts = [
        "-- 0014_benefit_vault_seed.sql",
        "-- GENERATED by scripts/build_vault_seed.py from data/reference/benefit_vault_registry.json. Do not edit.",
        f"-- Registry {registry['version']} as of {registry['as_of']}, sha256 {sha}.",
        "-- Apply after 0014, in one transaction, as the migration owner. Idempotent.",
        "",
        "INSERT INTO ref.vault_registry_meta (singleton, registry, version, as_of, sha256, notice) VALUES "
        f"(true, {lit(registry['registry'])}, {lit(registry['version'])}, {lit(registry['as_of'])}, {lit(sha)}, "
        f"{lit(registry['notice'])})\nON CONFLICT (singleton) DO UPDATE SET registry = EXCLUDED.registry, "
        "version = EXCLUDED.version, as_of = EXCLUDED.as_of, sha256 = EXCLUDED.sha256, notice = EXCLUDED.notice;",
        "",
    ]
    jur_cols = ["code", "name", "coverage", "benefit_count", "tail_unread_chars", "registry_sha256"]
    parts += upsert("ref.vault_jurisdiction", "code", jur_cols,
                    [[j["code"], j["name"], j["coverage"], j["benefit_count"], j["tail_unread_chars"], sha]
                     for j in registry["jurisdictions"]])
    src_cols = ["source_id", "url", "page_status", "tier", "opened_on", "seen_on", "page_updated",
                "tail_unread_chars", "registry_sha256"]
    parts += upsert("ref.vault_source", "source_id", src_cols,
                    [[s["source_id"], s["url"], s["page_status"], s["tier"], s["opened_on"], s["seen_on"],
                      s["page_updated"], s["tail_unread_chars"], sha] for s in registry["sources"]])
    fact_cols = ["fact_key", "data_class", "kind", "question", "session_only", "pullable", "registry_sha256"]
    parts += upsert("ref.vault_fact", "fact_key", fact_cols,
                    [[k, f["data_class"], f["kind"], f["question"], f["session_only"], f["pullable"], sha]
                     for k, f in sorted(registry["facts"].items())])
    ben_cols = ["benefit_id", "jurisdiction", "category", "kind", "title", "groups", "rule", "rule_tokens",
                "who_it_is_for", "value", "official_url", "official_url_status", "source_id", "source_tier",
                "record_status", "content_hash", "ledger_ref", "registry_sha256"]
    keep = ("ref.vault_benefit.record_status = 'VERIFIED' "
            "AND ref.vault_benefit.verified_content_hash = EXCLUDED.content_hash")
    ben_update = ", ".join(f"{c} = EXCLUDED.{c}" for c in ben_cols if c not in ("benefit_id", "record_status")) + (
        f", record_status = CASE WHEN {keep} THEN 'VERIFIED' ELSE EXCLUDED.record_status END"
        f", verified_by = CASE WHEN {keep} THEN ref.vault_benefit.verified_by END"
        f", verified_on = CASE WHEN {keep} THEN ref.vault_benefit.verified_on END"
        f", verified_content_hash = CASE WHEN {keep} THEN ref.vault_benefit.verified_content_hash END")
    parts += upsert("ref.vault_benefit", "benefit_id", ben_cols,
                    [[b["benefit_id"], b["jurisdiction"], b["category"], b["kind"], b["title"], b["groups"],
                      b["rule"], b["rule_tokens"], b["who_it_is_for"], b["value"], b["official_url"],
                      b["official_url_status"], b["source_id"], b["source_tier"], b["record_status"],
                      b["content_hash"], b["ledger_ref"], sha] for b in registry["benefits"]],
                    update_sql=ben_update)
    lead_cols = ["lead_id", "topic", "citation", "lead", "caveat", "record_status", "registry_sha256"]
    parts += upsert("ref.vault_rule_lead", "lead_id", lead_cols,
                    [[l["lead_id"], l["topic"], l["citation"], l["lead"], l["caveat"], l["record_status"], sha]
                     for l in registry["rule_leads"]])
    links = [[b["benefit_id"], lead] for b in registry["benefits"] for lead in b["lead_ids"]]
    parts.append("DELETE FROM ref.vault_benefit_lead;")
    if links:
        values = ", ".join(f"({lit(a)}, {lit(b)})" for a, b in links)
        parts.append(f"INSERT INTO ref.vault_benefit_lead (benefit_id, lead_id) VALUES {values};")
    cav_cols = ["caveat_id", "text", "registry_sha256"]
    parts += upsert("ref.vault_caveat", "caveat_id", cav_cols,
                    [[k, v, sha] for k, v in sorted(registry["caveats"].items())])
    lic = registry["license_reciprocity"]
    lic_cols = ["state", "teacher_full_reciprocity", "lawyer_ube", "real_estate", "record_status", "registry_sha256"]
    parts += upsert("ref.vault_license_reciprocity", "state", lic_cols,
                    [[code, row["teacher_full_reciprocity"], row["lawyer_ube"], row["real_estate"],
                      lic["record_status"], sha] for code, row in sorted(lic["states"].items())])
    agents = registry["governance"]["agents"]
    man_cols = ["agent_id", "name", "plane", "role", "may_issue_determinations", "may_pull_from_agents",
                "highest_class_held", "registry_sha256"]
    parts += upsert("ref.vault_agent_manifest", "agent_id", man_cols,
                    [[a["agent_id"], a["name"], a["plane"], a["role"], a["may_issue_determinations"],
                      a["may_pull_from_agents"], a["highest_class_held"], sha] for a in agents])
    parts.append("DELETE FROM ref.vault_agent_exposure;")
    exposures = [(a["agent_id"], e["fact_key"], e["data_class"]) for a in agents for e in a["exposes"]]
    if exposures:
        values = ", ".join(f"({lit(a)}, {lit(k)}, {lit(c)})" for a, k, c in exposures)
        parts.append(f"INSERT INTO ref.vault_agent_exposure (agent_id, fact_key, data_class) VALUES {values};")
    parts += [
        "",
        "-- Prune rows from older registries (children before parents).",
        f"DELETE FROM ref.vault_benefit WHERE registry_sha256 <> {lit(sha)};",
        f"DELETE FROM ref.vault_rule_lead WHERE registry_sha256 <> {lit(sha)};",
        f"DELETE FROM ref.vault_caveat WHERE registry_sha256 <> {lit(sha)};",
        f"DELETE FROM ref.vault_license_reciprocity WHERE registry_sha256 <> {lit(sha)};",
        f"DELETE FROM ref.vault_agent_manifest WHERE registry_sha256 <> {lit(sha)};",
        f"DELETE FROM ref.vault_source WHERE registry_sha256 <> {lit(sha)};",
        f"DELETE FROM ref.vault_jurisdiction WHERE registry_sha256 <> {lit(sha)};",
        f"DELETE FROM ref.vault_fact WHERE registry_sha256 <> {lit(sha)};",
        "",
        "DO $seedcheck$",
        "BEGIN",
        f"  IF (SELECT count(*) FROM ref.vault_benefit) <> {len(registry['benefits'])} THEN",
        "    RAISE EXCEPTION 'vault seed: benefit count does not match the registry';",
        "  END IF;",
        f"  IF (SELECT sha256 FROM ref.vault_registry_meta) <> {lit(sha)} THEN",
        "    RAISE EXCEPTION 'vault seed: registry hash does not match';",
        "  END IF;",
        "END",
        "$seedcheck$;",
        "",
    ]
    return "\n".join(parts)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    registry = json.loads(REGISTRY_PATH.read_text(encoding="utf-8"))
    text = render(registry)
    if args.check:
        current = SEED_PATH.read_text(encoding="utf-8") if SEED_PATH.exists() else ""
        if current != text:
            print("seed drift: run scripts/build_vault_seed.py", file=sys.stderr)
            return 1
        print("seed up to date")
        return 0
    SEED_PATH.parent.mkdir(parents=True, exist_ok=True)
    SEED_PATH.write_text(text, encoding="utf-8")
    print(f"wrote {SEED_PATH.relative_to(ROOT)} ({len(text.encode('utf-8'))} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
